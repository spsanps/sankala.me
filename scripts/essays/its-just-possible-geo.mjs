// Builds the map data for "It's just possible" (the seatback moving map on its cover and figure)
// from Natural Earth 1:50m, which is in the public domain (https://www.naturalearthdata.com/).
//
//   node scripts/essays/its-just-possible-geo.mjs <folder with the Natural Earth GeoJSON files>
//
// It expects ne_50m_land, ne_50m_lakes, ne_50m_admin_0_boundary_lines_land and
// ne_50m_admin_1_states_provinces_lines (saved as ne_50m_states_lines.geojson), from
// https://github.com/nvkelso/natural-earth-vector/tree/master/geojson. It clips everything to
// North America around the United States, simplifies it to about 4 km, and writes
// src/pages/notes/its-just-possible/flight/geo.js: rings and lines as delta-encoded
// integer lon/lat in hundredths of a degree.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('Usage: node scripts/essays/its-just-possible-geo.mjs <natural-earth-geojson-folder>'); process.exit(1); }
const root = fileURLToPath(new URL('../../', import.meta.url));
const BOX = { w: -150, e: -45, s: 12, n: 64 };
const TOL = 0.04;   // degrees

const read = async name => JSON.parse(await readFile(resolve(src, name + '.geojson'), 'utf8'));
const rings = f => f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates.flat() : [];
const lines = f => f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.type === 'MultiLineString' ? f.geometry.coordinates : [];

// Sutherland–Hodgman against the box: fine for filled shapes (edges along the box are off screen).
function clipRing(ring) {
  let pts = ring;
  const edges = [[p => p[0] >= BOX.w, (a, b) => at(a, b, 0, BOX.w)], [p => p[0] <= BOX.e, (a, b) => at(a, b, 0, BOX.e)], [p => p[1] >= BOX.s, (a, b) => at(a, b, 1, BOX.s)], [p => p[1] <= BOX.n, (a, b) => at(a, b, 1, BOX.n)]];
  for (const [inside, cross] of edges) {
    const out = [];
    for (let i = 0; i < pts.length; i++) {
      const a = pts[(i + pts.length - 1) % pts.length], b = pts[i];
      if (inside(b)) { if (!inside(a)) out.push(cross(a, b)); out.push(b); } else if (inside(a)) out.push(cross(a, b));
    }
    pts = out; if (!pts.length) return [];
  }
  return pts;
}
function at(a, b, axis, v) { const t = (v - a[axis]) / (b[axis] - a[axis]); return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]; }
const inBox = p => p[0] >= BOX.w && p[0] <= BOX.e && p[1] >= BOX.s && p[1] <= BOX.n;
function clipLine(line) {
  const out = []; let cur = [];
  for (const p of line) { if (inBox(p)) cur.push(p); else { if (cur.length > 1) out.push(cur); cur = []; } }
  if (cur.length > 1) out.push(cur);
  return out;
}
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop(); const [ax, ay] = pts[i], [bx, by] = pts[j]; const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-9;
    let best = -1, bd = 0;
    for (let k = i + 1; k < j; k++) { const d = Math.hypot(dx, dy) < 1e-9 ? Math.hypot(pts[k][0] - ax, pts[k][1] - ay) : Math.abs((pts[k][0] - ax) * dy - (pts[k][1] - ay) * dx) / L; if (d > bd) { bd = d; best = k; } }
    if (bd > tol) { keep[best] = 1; stack.push([i, best], [best, j]); }
  }
  return pts.filter((_, k) => keep[k]);
}
const encode = pts => { const q = pts.map(([x, y]) => [Math.round(x * 100), Math.round(y * 100)]); const out = [q[0][0], q[0][1]]; for (let i = 1; i < q.length; i++) { const dx = q[i][0] - q[i - 1][0], dy = q[i][1] - q[i - 1][1]; if (dx || dy) out.push(dx, dy); } return out; };
const area = r => { let a = 0; for (let i = 0; i < r.length; i++) { const p = r[i], q = r[(i + 1) % r.length]; a += p[0] * q[1] - q[0] * p[1]; } return Math.abs(a / 2); };

const polys = (fc, minArea) => fc.features.flatMap(rings).map(clipRing).filter(r => r.length > 2 && area(r) > minArea).map(r => encode(simplify(r.concat([r[0]]), TOL)));
const polylines = (fc, keepFeature = () => true) => fc.features.filter(keepFeature).flatMap(lines).flatMap(clipLine).map(l => simplify(l, TOL)).filter(l => l.length > 1).map(encode);

const land = polys(await read('ne_50m_land'), 0.02);
const lakes = polys(await read('ne_50m_lakes'), 0.05);
const borders = polylines(await read('ne_50m_admin_0_boundary_lines_land'));
const states = polylines(await read('ne_50m_states_lines'), f => ['USA', 'CAN', 'MEX'].includes(f.properties.ADM0_A3));

const body = `// GENERATED by scripts/essays/its-just-possible-geo.mjs from Natural Earth 1:50m (public domain).
// North America around the United States, simplified to about ${Math.round(TOL * 100)} km. Each shape is a flat list:
// the first lon/lat pair in hundredths of a degree, then the step to each next point.
export const LAND = ${JSON.stringify(land)};
export const LAKES = ${JSON.stringify(lakes)};
export const BORDERS = ${JSON.stringify(borders)};
export const STATES = ${JSON.stringify(states)};
`;
await mkdir(resolve(root, 'src/pages/notes/its-just-possible/flight'), { recursive: true });
await writeFile(resolve(root, 'src/pages/notes/its-just-possible/flight/geo.js'), body);
console.log(`land ${land.length}, lakes ${lakes.length}, borders ${borders.length}, states ${states.length}; ${(body.length / 1024).toFixed(1)} KB`);
